// MFA-SETUP-STEP-SR은 4단계 기준 문장이다. 입구 A는 3단계라 숫자만 바꾼다(기획서 1.3 D13 "입구별 계산").
export function stepSr(total: number, n: number, name: string): string {
  return fill(MFA_COPY['MFA-SETUP-STEP-SR'].replace('4단계 중', `${total}단계 중`), { n, '단계 이름': name });
}

export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{([^{}]+)\}/g, (m, k: string) => (k in values ? String(values[k]) : m));
}
