제1조 (목적)

본 약관은 주식회사 일리아(이하 "회사")가 운영하는 평생교육 서비스 바라 평생교육원(https://ylia.io, 이하 "서비스")의 이용과 관련하여 회사와 회원 간의 권리, 의무 및 책임사항, 기타 필요한 사항을 규정함을 목적으로 합니다.

제2조 (용어의 정의)

1. "서비스"란 회사가 온라인으로 제공하는 교육 강좌 및 이와 관련한 일체의 부수 서비스를 말합니다.
2. "회원"이란 본 약관에 동의하고 회사와 이용계약을 체결하여 서비스를 이용하는 자를 말합니다.
3. "강좌"란 회사가 서비스를 통해 제공하는 개별 교육 과정을 말하며, 하나의 강좌는 복수의 "강의"로 구성됩니다.
4. "수강 신청"이란 회원이 특정 강좌의 수강을 회사에 청약하는 행위를 말합니다.
5. "승인"이란 회사가 회원의 수강료 입금을 확인하고 수강 자격을 부여하는 행위를 말합니다.
6. "강의실"이란 승인된 회원이 강의 영상, 퀴즈, 과제 등 학습 콘텐츠를 이용할 수 있는 서비스 내 공간을 말합니다.

제3조 (약관의 게시와 개정)

1. 회사는 본 약관의 내용을 회원이 쉽게 확인할 수 있도록 서비스 화면에 게시합니다.
2. 회사는 관련 법령을 위배하지 않는 범위에서 본 약관을 개정할 수 있습니다.
3. 회사가 약관을 개정할 경우 적용일자 및 개정 사유를 명시하여 적용일자 7일 전부터 공지합니다. 다만 회원에게 불리한 내용으로 개정하는 경우에는 적용일자 30일 전부터 공지하고, 회원의 이메일 등으로 개별 통지합니다.
4. 회사가 제3항에 따라 개정 약관을 공지하면서 회원에게 30일 기간 내에 의사표시를 하지 않으면 동의한 것으로 본다는 뜻을 명확하게 고지하였음에도 회원이 명시적으로 거부의사를 표시하지 않은 경우, 회원이 개정 약관에 동의한 것으로 봅니다.
5. 회원은 개정 약관에 동의하지 않을 경우 이용계약을 해지(회원 탈퇴)할 수 있습니다.

제4조 (약관 외 준칙)

본 약관에 명시되지 않은 사항은 「전자상거래 등에서의 소비자보호에 관한 법률」, 「약관의 규제에 관한 법률」, 「전자문서 및 전자거래기본법」, 「개인정보 보호법」, 「평생교육법」 등 관련 법령과 상관례에 따릅니다. 관련 법령이 본 약관보다 회원에게 유리한 경우에는 해당 법령을 우선하여 적용합니다.

제5조 (회원가입 및 이용계약의 성립)

1. 이용계약은 가입을 희망하는 자가 본 약관 및 개인정보처리방침에 동의하고 회사가 정한 가입 양식(이름, 이메일, 비밀번호, 휴대전화번호)을 작성하여 신청하고, 회사가 이를 승낙함으로써 성립합니다.
2. 회사는 다음 각 호에 해당하는 신청에 대해서는 승낙을 거부하거나 사후에 이용계약을 해지할 수 있습니다.
   - 타인의 명의 또는 허위의 정보를 기재한 경우
   - 만 14세 미만인 경우 (회사는 만 14세 미만의 가입을 받지 않습니다)
   - 이전에 본 약관 위반으로 자격을 상실한 적이 있는 경우
   - 서비스의 정상적인 운영을 방해할 목적으로 신청한 경우
3. 회원은 가입 시 기재한 정보에 변경이 있는 경우 마이페이지에서 즉시 수정하여야 하며, 수정하지 않아 발생한 불이익에 대해 회사는 책임지지 않습니다.

제6조 (계정 관리 책임)

1. 회원의 계정(이메일)과 비밀번호에 관한 관리 책임은 회원 본인에게 있으며, 이를 제3자에게 양도·대여할 수 없습니다.
2. 회원은 자신의 계정이 부정하게 사용된 사실을 인지한 경우 즉시 회사에 통지하여야 하며, 회사는 통지를 받은 즉시 필요한 조치를 취합니다.

제7조 (서비스의 내용)

회사는 회원에게 다음의 서비스를 제공합니다.

1. 강좌 정보의 제공 및 검색
2. 수강 신청 및 무통장입금 안내
3. 강의실(강의 영상 시청, 학습 진도 관리)
4. 퀴즈 응시 및 과제 제출
5. 수료 판정 및 수료증 발급
6. 기타 회사가 추가로 개발하거나 제휴를 통해 제공하는 서비스

제8조 (서비스의 제공 시간 및 변경·중단)

1. 서비스는 연중무휴 1일 24시간 제공함을 원칙으로 합니다.
2. 회사는 시스템 점검, 설비의 보수·교체, 통신 두절 등 운영상 필요한 경우 서비스의 전부 또는 일부를 일시 중단할 수 있으며, 이 경우 사전에 공지합니다. 다만 사전 공지가 불가능한 긴급한 사유가 있는 경우에는 사후에 공지할 수 있습니다.
3. 회사는 강좌의 내용, 커리큘럼, 강사를 교육의 질을 높이기 위해 변경할 수 있으며, 회원에게 중대한 영향을 미치는 변경(강좌 폐지, 수강 기간 단축 등)의 경우 사전에 통지하고 제11조에 따라 환불합니다.

제9조 (수강 신청과 계약의 성립)

1. 회원은 강좌 상세 화면에서 강좌명, 수강료, 수강 정원, 커리큘럼을 확인하고 수강 신청을 할 수 있습니다.
2. 수강 신청은 회원의 청약이며, 수강 계약은 회사가 수강료 입금을 확인하여 승인한 시점에 성립합니다.
3. 수강 정원의 마감 여부는 입금 시점이 아니라 회사의 승인 시점을 기준으로 판단합니다. 따라서 입금 대기 중에 다른 회원의 승인으로 정원이 마감될 수 있습니다. 이 경우 회사는 해당 회원의 신청을 반려하고 입금액 전액을 환불하며, 반려 사유를 함께 안내합니다.
4. 동일한 강좌에 대해 이미 입금 대기 또는 수강 중인 신청이 있는 경우 중복 신청은 제한됩니다.
5. 회사는 승인 또는 반려 결과를 회원에게 서비스 화면 및 이메일 등으로 통지합니다. 반려 시에는 반드시 사유를 함께 안내합니다.

제10조 (수강료의 결제 — 무통장입금)

1. 수강료 결제는 무통장입금(계좌이체) 방식으로만 이루어집니다.
2. 회원은 수강 신청 후 안내된 계좌로 신청일로부터 3일(72시간) 이내에 수강료 전액을 입금하여야 합니다.
3. 입금 시에는 신청자 본인의 이름으로 입금하여야 합니다. 입금자명이 신청자 이름과 다른 경우 입금 확인이 지연되거나 불가능할 수 있으며, 이 경우 회원은 고객센터로 입금 사실을 알려야 합니다.
4. 제2항의 기한 내에 입금이 확인되지 않은 신청은 자동으로 만료되며, 회원은 해당 강좌에 다시 신청할 수 있습니다. 다만 재신청 시점에 정원이 마감되었거나 강좌가 종료된 경우에는 신청이 제한될 수 있습니다.
5. 회사는 입금 확인 후 영업일 기준으로 지체 없이 승인 여부를 처리합니다.
6. 회사는 카드 결제, 간편결제 등 다른 결제수단을 향후 추가할 수 있으며, 이 경우 서비스 화면을 통해 안내합니다.

제11조 (청약철회 및 환불)

1. 수강 시작 전 취소: 회원은 승인 후 강의실 이용을 시작하기 전이라면 언제든지 수강을 취소할 수 있으며, 회사는 납입한 수강료 전액을 환불합니다. 관련 법령에 따른 청약철회권(계약 내용에 관한 서면을 받은 날부터 7일 이내)은 이와 별도로 보장됩니다.
2. 승인이 이루어지지 않은 경우: 정원 마감, 강좌 미개설 등 회사의 사유로 신청이 반려된 경우 입금액 전액을 환불합니다.
3. 수강 시작 후 환불: 회원이 강의실 이용을 시작한 이후의 환불은 해당 강좌의 총 수강 기간을 기준으로 다음과 같이 처리합니다.
   - 총 수강 기간의 1/3 경과 전: 수강료의 2/3
   - 총 수강 기간의 1/2 경과 전: 수강료의 1/2
   - 총 수강 기간의 1/2 경과 후: 환불하지 않음
4. 회사 사유로 인한 중단: 강좌의 폐지, 회사의 귀책사유로 인한 수업 불가 등으로 회원이 학습을 계속할 수 없게 된 경우, 회사는 잔여 수강 기간에 해당하는 수강료 전액을 환불합니다.
5. 환불 신청 방법: 환불은 고객센터(info@ylia.io / 010-9025-5093)를 통해 신청하며, 회원이 지정한 본인 명의의 계좌로 지급합니다. 회사는 환불 사유 확인 후 영업일 기준 3일 이내에 환불을 완료합니다.
6. 회원이 부정한 방법으로 강좌를 이용하거나 제14조를 위반하여 이용이 제한된 경우, 환불이 제한될 수 있습니다.
